CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(32) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE mission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    destination VARCHAR(255) NOT NULL,
    secret_code TEXT NOT NULL,
    status VARCHAR(32) NOT NULL,
    driver_id BIGINT NOT NULL,
    dispatcher_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_mission_driver FOREIGN KEY (driver_id) REFERENCES app_user(id),
    CONSTRAINT fk_mission_dispatcher FOREIGN KEY (dispatcher_id) REFERENCES app_user(id)
);

CREATE INDEX idx_mission_driver_created_at ON mission(driver_id, created_at);
CREATE INDEX idx_mission_dispatcher_created_at ON mission(dispatcher_id, created_at);

CREATE TABLE document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mission_id BIGINT NOT NULL,
    file_path VARCHAR(255) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    mime_type VARCHAR(255) NOT NULL,
    uploaded_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_document_mission FOREIGN KEY (mission_id) REFERENCES mission(id)
);

CREATE INDEX idx_document_mission_uploaded_at ON document(mission_id, uploaded_at);

CREATE TABLE refresh_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token VARCHAR(100) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL UNIQUE,
    expiry_date TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_refresh_token_user FOREIGN KEY (user_id) REFERENCES app_user(id)
);

CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    email VARCHAR(255),
    action VARCHAR(255) NOT NULL,
    ip_address VARCHAR(255) NOT NULL,
    status_code INTEGER NOT NULL,
    timestamp TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_audit_log_timestamp ON audit_log(timestamp);
